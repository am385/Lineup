using System.Text.Json;
using Lineup.Common.Streaming;

namespace Lineup.Common.Configuration;

/// <summary>Identifies the frontend-neutral editor used for one adapter setting.</summary>
public enum AdapterSettingKind
{
    /// <summary>Single-line text.</summary>
    Text,

    /// <summary>Absolute or relative URI text.</summary>
    Uri,

    /// <summary>Absolute or relative filesystem path.</summary>
    FilePath,

    /// <summary>Absolute or relative filesystem directory path.</summary>
    DirectoryPath,

    /// <summary>Whole number.</summary>
    Integer,

    /// <summary>Boolean value.</summary>
    Boolean,

    /// <summary>One value selected from a fixed set.</summary>
    Choice,

    /// <summary>GUID value.</summary>
    Guid,

    /// <summary>Masked secret supplied by the user.</summary>
    Secret,

    /// <summary>Secret generated by the plugin and shown once by the frontend.</summary>
    GeneratedSecret,

    /// <summary>SHA-256 certificate fingerprint.</summary>
    CertificateFingerprint
}

/// <summary>Identifies how a submitted adapter setting changes persisted configuration.</summary>
public enum AdapterSettingEditAction
{
    /// <summary>Preserve the currently persisted value.</summary>
    Preserve,

    /// <summary>Set the supplied value.</summary>
    Set,

    /// <summary>Clear the persisted value.</summary>
    Clear,

    /// <summary>Ask the plugin to generate and persist a new secret representation.</summary>
    Generate
}

/// <summary>Identifies a comparison used to conditionally display one setting.</summary>
public enum AdapterSettingConditionOperator
{
    /// <summary>The controlling value must equal the expected value.</summary>
    Equals,

    /// <summary>The controlling value must not equal the expected value.</summary>
    NotEquals
}

/// <summary>One selectable adapter-setting value.</summary>
public sealed record AdapterSettingChoice
{
    /// <summary>Gets the serialized value submitted to the plugin.</summary>
    public required string Value { get; init; }

    /// <summary>Gets the user-facing choice label.</summary>
    public required string Label { get; init; }
}

/// <summary>Controls whether one adapter setting is visible.</summary>
public sealed record AdapterSettingCondition
{
    /// <summary>Gets the key of the controlling setting.</summary>
    public required string FieldKey { get; init; }

    /// <summary>Gets the comparison operation.</summary>
    public AdapterSettingConditionOperator Operator { get; init; }

    /// <summary>Gets the serialized comparison value.</summary>
    public required string Value { get; init; }
}

/// <summary>Describes one portable adapter-configuration field.</summary>
public sealed record AdapterSettingDescriptor
{
    /// <summary>Gets the stable field key.</summary>
    public required string Key { get; init; }

    /// <summary>Gets the user-facing label.</summary>
    public required string Label { get; init; }

    /// <summary>Gets optional explanatory text.</summary>
    public string? Description { get; init; }

    /// <summary>Gets the frontend-neutral editor kind.</summary>
    public AdapterSettingKind Kind { get; init; }

    /// <summary>Gets whether a non-empty value is required.</summary>
    public bool IsRequired { get; init; }

    /// <summary>Gets whether an empty value may be submitted as a clear operation.</summary>
    public bool CanClear { get; init; } = true;

    /// <summary>Gets the optional minimum integer value.</summary>
    public long? Minimum { get; init; }

    /// <summary>Gets the optional maximum integer value.</summary>
    public long? Maximum { get; init; }

    /// <summary>Gets the available choices for a choice field.</summary>
    public IReadOnlyList<AdapterSettingChoice> Choices { get; init; } = [];

    /// <summary>Gets optional visibility conditions. All conditions must match.</summary>
    public IReadOnlyList<AdapterSettingCondition> VisibleWhen { get; init; } = [];
}

/// <summary>Describes all editable settings for one adapter kind.</summary>
public sealed record AdapterSettingsDescriptor
{
    /// <summary>Gets the adapter kind described by this schema.</summary>
    public required string AdapterKind { get; init; }

    /// <summary>Gets the ordered editable fields.</summary>
    public IReadOnlyList<AdapterSettingDescriptor> Fields { get; init; } = [];
}

/// <summary>One current adapter-setting value returned to a frontend.</summary>
public sealed record AdapterSettingSnapshot
{
    /// <summary>Gets the stable field key.</summary>
    public required string Key { get; init; }

    /// <summary>Gets the current non-secret value. Secret values must be omitted.</summary>
    public JsonElement? Value { get; init; }

    /// <summary>Gets whether a secret value is currently configured.</summary>
    public bool HasValue { get; init; }
}

/// <summary>Current editable values for one adapter configuration.</summary>
public sealed record AdapterSettingsSnapshot
{
    /// <summary>Gets the adapter kind represented by this snapshot.</summary>
    public required string AdapterKind { get; init; }

    /// <summary>Gets current values keyed by descriptor key.</summary>
    public IReadOnlyList<AdapterSettingSnapshot> Values { get; init; } = [];
}

/// <summary>One frontend-submitted adapter-setting mutation.</summary>
public sealed record AdapterSettingEdit
{
    /// <summary>Gets the stable field key.</summary>
    public required string Key { get; init; }

    /// <summary>Gets the requested mutation.</summary>
    public AdapterSettingEditAction Action { get; init; }

    /// <summary>Gets the submitted value for <see cref="AdapterSettingEditAction.Set"/>.</summary>
    public JsonElement? Value { get; init; }
}

/// <summary>Result of applying frontend edits through a plugin.</summary>
public sealed record AdapterSettingsApplyResult
{
    /// <summary>Gets the updated configuration when all edits are valid.</summary>
    public AdapterConfiguration? Configuration { get; init; }

    /// <summary>Gets validation failures keyed by field where possible.</summary>
    public IReadOnlyDictionary<string, IReadOnlyList<string>> Errors { get; init; } =
        new Dictionary<string, IReadOnlyList<string>>(StringComparer.Ordinal);

    /// <summary>Gets generated plaintext secrets that frontends may show once.</summary>
    public IReadOnlyDictionary<string, string> GeneratedSecrets { get; init; } =
        new Dictionary<string, string>(StringComparer.Ordinal);

    /// <summary>Gets whether a new configuration was produced.</summary>
    public bool Succeeded => Configuration is not null && Errors.Count == 0;
}

/// <summary>Describes one safely displayable adapter access grant.</summary>
public sealed record AdapterAccessGrantSnapshot
{
    /// <summary>Gets the stable grant identifier.</summary>
    public required Guid Id { get; init; }

    /// <summary>Gets the user-facing grant name.</summary>
    public required string Name { get; init; }

    /// <summary>Gets when the grant was created in UTC.</summary>
    public required DateTime CreatedAtUtc { get; init; }

    /// <summary>Gets when the grant token was last rotated in UTC.</summary>
    public DateTime? RotatedAtUtc { get; init; }

    /// <summary>Gets when the grant expires in UTC.</summary>
    public DateTime? ExpiresAtUtc { get; init; }

    /// <summary>Gets when the grant was revoked in UTC.</summary>
    public DateTime? RevokedAtUtc { get; init; }
}

/// <summary>Returns one adapter access-grant mutation without persisting its generated secret.</summary>
public sealed record AdapterAccessGrantMutationResult
{
    /// <summary>Gets the updated adapter configuration when the mutation succeeded.</summary>
    public AdapterConfiguration? Configuration { get; init; }

    /// <summary>Gets the affected grant when the mutation succeeded.</summary>
    public AdapterAccessGrantSnapshot? Grant { get; init; }

    /// <summary>Gets the generated plaintext token that may be shown once.</summary>
    public string? GeneratedSecret { get; init; }

    /// <summary>Gets validation failures.</summary>
    public IReadOnlyList<string> Errors { get; init; } = [];

    /// <summary>Gets whether the mutation succeeded.</summary>
    public bool Succeeded => Configuration is not null && Grant is not null && Errors.Count == 0;
}
